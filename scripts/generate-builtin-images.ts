/**
 * Scan public/images and write src/data/builtin-images.generated.ts
 * Run: npx vite-node scripts/generate-builtin-images.ts
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, extname, join, relative } from 'node:path';
import imageSize from 'image-size';
import type { ImageOrientation } from '../src/data/image-assets';
import {
  assertFormatMatchesOrientation,
  parseBuiltinImageBasename,
  sizeTokenToDimensions,
} from '../src/data/builtin-image-filename';

function detectOrientation(width: number, height: number): ImageOrientation {
  if (width === height) return 'square';
  return width > height ? 'landscape' : 'portrait';
}

const PROJECT_ROOT = process.cwd();
const IMAGES_DIR = join(PROJECT_ROOT, 'public', 'images');
const OUT_FILE = join(PROJECT_ROOT, 'src', 'data', 'builtin-images.generated.ts');

const ALLOWED_EXT = new Set(['.png', '.jpg', '.jpeg', '.webp', '.gif', '.avif']);

const MIME_BY_EXT: Record<string, string> = {
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.gif': 'image/gif',
  '.avif': 'image/avif',
};

function collectImageFiles(dir: string): string[] {
  const entries = readdirSync(dir, { withFileTypes: true });
  const files: string[] = [];
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...collectImageFiles(full));
      continue;
    }
    if (!entry.isFile()) continue;
    const ext = extname(entry.name).toLowerCase();
    if (ALLOWED_EXT.has(ext)) files.push(full);
  }
  return files.sort();
}

function posixUrlPath(relativeToPublic: string): string {
  return `/${relativeToPublic.split(/[/\\]/).join('/')}`;
}

function buildEntry(absPath: string): Record<string, unknown> {
  const fileName = basename(absPath);
  const ext = extname(fileName).toLowerCase();
  const base = basename(fileName, ext);
  const parsed = parseBuiltinImageBasename(base);

  const buffer = readFileSync(absPath);
  const measured = imageSize(buffer);
  if (!measured.width || !measured.height) {
    throw new Error(`Could not read image dimensions: ${absPath}`);
  }

  const fileDims = { width: measured.width, height: measured.height };
  const { width, height } = sizeTokenToDimensions(parsed.sizeToken, fileDims);
  const orientation = detectOrientation(width, height);
  assertFormatMatchesOrientation(parsed.logicalFormat, orientation, base);

  const relFromPublic = relative(join(PROJECT_ROOT, 'public'), absPath);
  const url = posixUrlPath(relFromPublic);

  return {
    id: base,
    name: fileName,
    url,
    width,
    height,
    orientation,
    source: 'starter',
    logicalName: parsed.logicalName,
    logicalFormat: parsed.logicalFormat,
    sizeToken: parsed.sizeToken,
    mimeType: MIME_BY_EXT[ext],
  };
}

function main(): void {
  const paths = collectImageFiles(IMAGES_DIR);
  if (paths.length === 0) {
    throw new Error(`No builtin images found in ${IMAGES_DIR}`);
  }

  const seenIds = new Set<string>();
  const assets: Record<string, unknown>[] = [];

  for (const absPath of paths) {
    const entry = buildEntry(absPath);
    const id = entry.id as string;
    if (seenIds.has(id)) {
      throw new Error(`Duplicate builtin image id: ${id}`);
    }
    seenIds.add(id);
    assets.push(entry);
  }

  const body = `// @generated by scripts/generate-builtin-images.ts — do not edit manually.
import type { ImageAsset } from './image-assets';

/** Auto-generated from public/images — do not edit manually. */
export const BUILTIN_IMAGES: ImageAsset[] = ${JSON.stringify(assets, null, 2)} as ImageAsset[];
`;

  writeFileSync(OUT_FILE, body, 'utf8');
  console.log(`Wrote ${assets.length} builtin image(s) to ${relative(PROJECT_ROOT, OUT_FILE)}`);
}

main();
