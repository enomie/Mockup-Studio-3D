/**
 * Convert built-in profile SVGs (public/profiles/lathe and extrude) into editable profile data
 * and write src/data/builtin-profiles.generated.ts. The SVG files stay the source of truth.
 * Run: npx tsx scripts/generate-builtin-profiles.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { JSDOM } from 'jsdom';
import { importProfilePathsFromSvg } from '../src/engine/profile-svg-import.ts';
import { builtinPathName } from '../src/scene/builtin-profile-path-names.ts';
import { roundProfilePaths } from '../src/scene/profile-model.ts';
import { BUILTIN_PROFILE_FILES } from '../src/scene/builtin-profile-files.ts';

globalThis.DOMParser = new JSDOM().window.DOMParser;

const PROJECT_ROOT = process.cwd();
const PROFILES_DIR = join(PROJECT_ROOT, 'public', 'profiles');
const OUT_FILE = join(PROJECT_ROOT, 'src', 'data', 'builtin-profiles.generated.ts');

export function renderBuiltinProfilesModule(): string {
  const entries = BUILTIN_PROFILE_FILES.map((entry) => {
    const svg = readFileSync(join(PROFILES_DIR, entry.dir, entry.file), 'utf8');
    const paths = importProfilePathsFromSvg(svg, (slot) => builtinPathName(entry.usedBy, slot));
    const json = JSON.stringify(roundProfilePaths(paths));
    return `  '${entry.id}': ${json},`;
  });
  return `// @generated by scripts/generate-builtin-profiles.ts — do not edit manually.
import type { ProfilePath } from '@/scene/profile-model';

/** Editable paths of the built-in profiles, converted from public/profiles/{lathe,extrude}/*.svg. */
export const BUILTIN_PROFILE_PATHS: Record<string, ProfilePath[]> = {
${entries.join('\n')}
};
`;
}

if (process.argv[1]?.endsWith('generate-builtin-profiles.ts')) {
  writeFileSync(OUT_FILE, renderBuiltinProfilesModule(), 'utf8');
  console.log(`Wrote ${OUT_FILE}`);
}
