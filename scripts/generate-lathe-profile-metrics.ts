/**
 * Measure built-in lathe SVGs (public/profiles/lathe, 1 unit = 1 mm) and write
 * src/data/lathe-profile-metrics.generated.ts so sizes are available synchronously.
 * The SVG files stay the single source of truth; this file is derived.
 * Run: npx tsx scripts/generate-lathe-profile-metrics.ts
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { JSDOM } from 'jsdom';
import { measureLatheSvgMm } from '../src/engine/lathe-svg-metrics.ts';

globalThis.DOMParser = new JSDOM().window.DOMParser;

const PROJECT_ROOT = process.cwd();
const LATHE_DIR = join(PROJECT_ROOT, 'public', 'profiles', 'lathe');
const OUT_FILE = join(PROJECT_ROOT, 'src', 'data', 'lathe-profile-metrics.generated.ts');

export function renderLatheProfileMetricsModule(): string {
  const files = readdirSync(LATHE_DIR)
    .filter((f) => f.endsWith('.svg'))
    .sort();
  const entries = files.map((file) => {
    const metrics = measureLatheSvgMm(readFileSync(join(LATHE_DIR, file), 'utf8'));
    return `  '${file}': ${JSON.stringify(metrics)},`;
  });
  return `// @generated by scripts/generate-lathe-profile-metrics.ts — do not edit manually.
import type { LatheSvgMetricsMm } from '@/engine/lathe-svg-metrics';

/** Measured from public/profiles/lathe/*.svg (mm). Regenerate after editing an SVG. */
export const LATHE_PROFILE_METRICS_MM: Record<string, LatheSvgMetricsMm> = {
${entries.join('\n')}
};
`;
}

if (process.argv[1]?.endsWith('generate-lathe-profile-metrics.ts')) {
  writeFileSync(OUT_FILE, renderLatheProfileMetricsModule(), 'utf8');
  console.log(`Wrote ${OUT_FILE}`);
}
